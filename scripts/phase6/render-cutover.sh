#!/usr/bin/env bash

set -euo pipefail

script_dir=$(cd "$(dirname "$0")" && pwd)
# shellcheck source=_common.sh
. "$script_dir/_common.sh"

config=
inventory=
soak_report=

while [ "$#" -gt 0 ]; do
    case "$1" in
        --dry-run) : ;;
        --config) shift; config=${1:-} ;;
        --inventory) shift; inventory=${1:-} ;;
        --soak-report) shift; soak_report=${1:-} ;;
        -h|--help)
            printf 'Usage: phase6 render-cutover --config FILE --inventory FILE --soak-report FILE\n'
            exit 0
            ;;
        *) phase6_die "$PHASE6_EXIT_GATE" "Unknown render-cutover option: $1" ;;
    esac
    shift
done

phase6_require_command jq
phase6_load_config "$config"
phase6_begin_report render-cutover

topology=${PHASE6_TOPOLOGY:-}
if [ -n "$inventory" ]; then
    [ -f "$inventory" ] || phase6_die "$PHASE6_EXIT_GATE" 'Inventory file does not exist'
    topology=$(jq -r '.ingress.topology // "unknown"' "$inventory")
fi
topology=${topology:-unknown}

blocked_reason=
case "$topology" in
    external-nginx) : ;;
    direct-bind) blocked_reason='Direct-bound host ports 80/443 are unsupported; no firewall redirect will be generated.' ;;
    external-traefik) blocked_reason='External Traefik cutover needs a topology-specific validated file-provider path and is not generated by this runbook.' ;;
    free) blocked_reason='No existing external front proxy was detected; live cutover is not safe.' ;;
    *) blocked_reason='Ingress topology is unknown or unsupported.' ;;
esac

if [ -n "$blocked_reason" ]; then
    jq -n --arg topology "$topology" --arg reason "$blocked_reason" \
        '{status:"BLOCKED",topology:$topology,reason:$reason,commandsGenerated:false,firewallChanges:false}' \
        > "$PHASE6_REPORT_DIR/cutover.json"
    printf '# Phase 6 live cutover\n\n- Status: BLOCKED\n- Topology: %s\n- Reason: %s\n- Commands executed: no\n' "$topology" "$blocked_reason" > "$PHASE6_REPORT_DIR/summary.md"
    phase6_write_status render-cutover dry-run BLOCKED
    phase6_error "$blocked_reason"
    exit "$PHASE6_EXIT_TOPOLOGY"
fi

[ -n "$soak_report" ] && [ -f "$soak_report" ] || phase6_die "$PHASE6_EXIT_GATE" 'A successful --soak-report is required'
jq -e '.status == "PASS" and .failures == 0 and .planned5xxAllowance == 0' "$soak_report" >/dev/null \
    || phase6_die "$PHASE6_EXIT_GATE" 'Soak report did not pass the zero-failure gate'
phase6_require_var PHASE6_PROXY_CONFIG
phase6_require_var PHASE6_CANDIDATE_CONFIG
[[ "$PHASE6_PROXY_CONFIG" = /* && "$PHASE6_CANDIDATE_CONFIG" = /* ]] \
    || phase6_die "$PHASE6_EXIT_GATE" 'Proxy configuration paths must be absolute'
[[ "$PHASE6_PROXY_CONFIG" != *$'\n'* && "$PHASE6_CANDIDATE_CONFIG" != *$'\n'* ]] \
    || phase6_die "$PHASE6_EXIT_GATE" 'Proxy configuration paths contain unsafe newlines'
[[ "$PHASE6_CANDIDATE_HTTP_PORT" =~ ^[0-9]+$ && "$PHASE6_CANDIDATE_HTTPS_PORT" =~ ^[0-9]+$ ]] \
    || phase6_die "$PHASE6_EXIT_GATE" 'Candidate ports must be numeric'
[ "$PHASE6_CANDIDATE_HTTP_PORT" -ge 1024 ] && [ "$PHASE6_CANDIDATE_HTTP_PORT" -le 65535 ] \
    && [ "$PHASE6_CANDIDATE_HTTPS_PORT" -ge 1024 ] && [ "$PHASE6_CANDIDATE_HTTPS_PORT" -le 65535 ] \
    || phase6_die "$PHASE6_EXIT_GATE" 'Candidate ports must be between 1024 and 65535'
[[ "$PHASE6_CANDIDATE_NETWORK" =~ ^[A-Za-z0-9][A-Za-z0-9_.-]{0,127}$ ]] \
    || phase6_die "$PHASE6_EXIT_GATE" 'Candidate validation network name is unsafe'

shell_quote() {
    printf "'%s'" "${1//\'/\'\"\'\"\'}"
}

active_q=$(shell_quote "$PHASE6_PROXY_CONFIG")
candidate_q=$(shell_quote "$PHASE6_CANDIDATE_CONFIG")
domain_q=$(shell_quote "$PHASE6_PRODUCTION_DOMAIN")
approval_q=$(shell_quote "$PHASE6_RUN_ID:$PHASE6_PRODUCTION_DOMAIN")
network_q=$(shell_quote "$PHASE6_CANDIDATE_NETWORK")
backup_path="$PHASE6_PROXY_CONFIG.phase6-$PHASE6_RUN_ID.rollback"
backup_q=$(shell_quote "$backup_path")
plan="$PHASE6_REPORT_DIR/cutover-plan.sh"

cat > "$plan" <<EOF
#!/usr/bin/env bash
set -euo pipefail

# GENERATED ONLY. Review this file and the referenced candidate config before use.
# It deliberately performs no legacy cleanup.
test "\${PHASE6_APPROVE_LIVE_SWITCH:-}" = $approval_q || {
  echo 'Exact PHASE6_APPROVE_LIVE_SWITCH approval is required' >&2
  exit 2
}

active_config=$active_q
candidate_config=$candidate_q
rollback_config=$backup_q
production_domain=$domain_q
candidate_network=$network_q

test -f "\$active_config"
test -f "\$candidate_config"
test "\$(docker network inspect -f '{{.Internal}}' "\$candidate_network")" = true
ss -H -ltn | grep -Eq "127\\.0\\.0\\.1:$PHASE6_CANDIDATE_HTTP_PORT([[:space:]]|$)"
ss -H -ltn | grep -Eq "127\\.0\\.0\\.1:$PHASE6_CANDIDATE_HTTPS_PORT([[:space:]]|$)"
curl --fail --silent --show-error --resolve "\$production_domain:$PHASE6_CANDIDATE_HTTP_PORT:127.0.0.1" \
  "http://\$production_domain:$PHASE6_CANDIDATE_HTTP_PORT/" >/dev/null
curl --fail --silent --show-error --resolve "\$production_domain:$PHASE6_CANDIDATE_HTTPS_PORT:127.0.0.1" \
  "https://\$production_domain:$PHASE6_CANDIDATE_HTTPS_PORT/" >/dev/null

sudo cp --preserve=mode,ownership,timestamps "\$active_config" "\$rollback_config"
next_config="\$active_config.phase6-next"
sudo install -m 0644 "\$candidate_config" "\$next_config"
sudo mv "\$next_config" "\$active_config"

if ! sudo nginx -t; then
  sudo cp "\$rollback_config" "\$active_config"
  exit 4
fi
sudo nginx -s reload

if ! curl --fail --silent --show-error --max-time 20 "https://\$production_domain/" >/dev/null; then
  sudo cp "\$rollback_config" "\$active_config"
  sudo nginx -t
  sudo nginx -s reload
  exit 4
fi

echo 'Traffic switch passed. Keep rollback_config for at least 72 hours.'
echo "Rollback command: sudo cp '\$rollback_config' '\$active_config' && sudo nginx -t && sudo nginx -s reload"
EOF
chmod 700 "$plan"

jq -n \
    --arg runId "$PHASE6_RUN_ID" \
    --arg topology "$topology" \
    --arg productionDomain "$PHASE6_PRODUCTION_DOMAIN" \
    --arg plan "$plan" \
    --arg rollbackConfig "$backup_path" \
    '{runId:$runId,status:"READY_FOR_REVIEW",topology:$topology,productionDomain:$productionDomain,commandsGenerated:true,commandsExecuted:false,plan:$plan,rollbackConfig:$rollbackConfig,rollbackWindowHours:72,automaticCleanup:false,firewallChanges:false}' \
    > "$PHASE6_REPORT_DIR/cutover.json"
cat > "$PHASE6_REPORT_DIR/summary.md" <<EOF
# Phase 6 live cutover plan

- Status: READY FOR REVIEW
- Topology: $topology
- Production domain: $PHASE6_PRODUCTION_DOMAIN
- Commands generated: yes
- Commands executed: no
- Firewall changes: no
- Automatic cleanup: no
- Minimum rollback window: 72 hours
EOF
phase6_write_status render-cutover dry-run READY_FOR_REVIEW
phase6_log "Cutover commands generated but not executed: $plan"
